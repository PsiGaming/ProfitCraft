#!/usr/bin/env python3
"""Writes Sources/NoVendorValue.lua: items no merchant takes although the item data gives them a sell price.

Source: Forever's ItemSparse table as exported by wago.tools (product "wowf"). An item goes on the list when its
SellPrice is above 0 and bit 0x1000 of Flags_1 is set (TrinityCore names that bit ITEM_FLAG2_NO_VENDOR_VALUE).
Confirmed in game for Blinding Powder and Strange Dust (2026-11-24: both flagged, both learned as
unsellable from the bag API's hasNoValue). Items with SellPrice 0 aren't listed: they count 0 anyway.

Run after a Forever patch (from the addon folder):
    python3 -I plan/tools/no_vendor_value.py            # newest wowf build on wago.tools
    python3 -I plan/tools/no_vendor_value.py 1.60.1.71091
The download goes to a fresh temp folder and is only parsed as CSV.
"""
import csv
import io
import json
import pathlib
import sys
import tempfile
import urllib.request

NO_VENDOR_VALUE = 0x1000
HEADERS = {"User-Agent": "Mozilla/5.0"}
OUT = pathlib.Path(__file__).resolve().parents[2] / "Sources" / "NoVendorValue.lua"


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=HEADERS), timeout=120) as response:
        return response.read()


def latest_build():
    return json.loads(fetch("https://wago.tools/api/builds"))["wowf"][0]["version"]


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else latest_build()
    with tempfile.TemporaryDirectory() as folder:
        path = pathlib.Path(folder) / "ItemSparse.csv"
        path.write_bytes(fetch(f"https://wago.tools/db2/ItemSparse/csv?build={build}"))
        rows = list(csv.DictReader(io.StringIO(path.read_text(encoding="utf-8"), newline="")))
    if not rows or "Flags_1" not in rows[0] or "SellPrice" not in rows[0]:
        sys.exit(f"unexpected ItemSparse export for build {build}")
    items = sorted(
        (int(r["ID"]), " ".join(r["Display_lang"].split()))  # names on one line (they go into comments)
        for r in rows
        if int(r["SellPrice"]) > 0 and int(r["Flags_1"]) & NO_VENDOR_VALUE
    )
    lines = [
        "-- ProfitCraft: items no merchant takes although the item data gives them a sell price.",
        "-- GENERATED by plan/tools/no_vendor_value.py; don't edit by hand, run the script again after a Forever patch.",
        f"-- Source: Forever's ItemSparse table (wago.tools, product wowf, build {build}): sell price above 0 and the",
        "-- \"no vendor value\" flag (Flags_1 bit 0x1000). Confirmed in game for Blinding Powder and Strange Dust.",
        "",
        "local _, PC = ...",
        "",
        f'PC.NO_VENDOR_VALUE_BUILD = "{build}"',
        "-- The highest item ID in that data: items up to it count as checked by it (Items:IsVerifiedSellable).",
        f"PC.NO_VENDOR_VALUE_MAX_ID = {max(int(r['ID']) for r in rows)}",
        "PC.NO_VENDOR_VALUE = {",
    ]
    lines += [f"  [{item_id}] = true, -- {name}" for item_id, name in items]
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT}: {len(items)} items from build {build}")


if __name__ == "__main__":
    main()
